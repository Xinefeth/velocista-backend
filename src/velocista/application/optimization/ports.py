from typing import Protocol


class OptimizationRepository(Protocol):
    def list_controllers(self) -> list[dict]: ...
    def get_controller(self, controller_id: str) -> dict | None: ...
    def version_robot(self, version_id: int) -> str | None: ...
    def list_setups(
        self, robot_id: str, limit: int, offset: int, version_id: int | None
    ) -> dict: ...
    def create_setup(self, robot_id: str, values: dict, controller: dict) -> dict: ...
    def get_setup(self, setup_id: int) -> dict | None: ...
    def archive_setup(self, setup_id: int) -> None: ...
