"""Alembic usa los modelos registrados y admite conexiones aisladas para verificación."""

from alembic import context

import velocista.infrastructure.persistence.models  # noqa: F401
from velocista.infrastructure.persistence.db import Base, engine

target_metadata = Base.metadata


def migrate(connection):
    context.configure(connection=connection, target_metadata=target_metadata, compare_type=True)
    with context.begin_transaction():
        context.run_migrations()


if context.is_offline_mode():
    context.configure(
        url=engine.url.render_as_string(hide_password=False),
        target_metadata=target_metadata,
        literal_binds=True,
        dialect_opts={"paramstyle": "named"},
        compare_type=True,
    )
    with context.begin_transaction():
        context.run_migrations()
elif context.config.attributes.get("connection") is not None:
    migrate(context.config.attributes["connection"])
else:
    with engine.connect() as connection:
        migrate(connection)
